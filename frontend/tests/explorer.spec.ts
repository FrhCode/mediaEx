test('parking the pointer on the scrubber holds the bar while the preview is open', async ({ page }) => {
  await login(page)
  await page.clock.install()
  await openVideo(page)
  await ensurePlaying(page)
  const controls = page.locator('.player-controls')
  const preview = page.locator('.seek-preview')
  const box = (await page.getByRole('slider', { name: 'Seek', exact: true }).boundingBox())!

  // The preview renders outside the control bar, so letting the bar fade here left a
  // frame floating over the video with no controls beneath it.
  await page.mouse.move(box.x + box.width * 0.4, box.y + box.height / 2)
  await expect(preview).toBeVisible()
  await page.clock.runFor(6_000)
  await expect(controls).toHaveAttribute('aria-hidden', 'false')

  await page.mouse.move(box.x, box.y - 200)
  await expect(preview).toHaveCount(0)
  await page.clock.runFor(4_000)
  await expect(controls).toHaveAttribute('aria-hidden', 'true')
})
