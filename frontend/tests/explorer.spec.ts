for (const storage of ['invalid', 'unavailable'] as const) {
  test(`media feed is the fallback when local storage is ${storage}`, async ({ page }) => {
    await page.addInitScript((state) => {
      if (state === 'invalid') localStorage.setItem('mediaex:library-mode', 'not-a-mode')
      else {
        const getItem = Storage.prototype.getItem
        const setItem = Storage.prototype.setItem
        Storage.prototype.getItem = function (key) {
          if (key === 'mediaex:library-mode') throw new DOMException('Blocked', 'SecurityError')
          return getItem.call(this, key)
        }
        Storage.prototype.setItem = function (key, value) {
          if (key === 'mediaex:library-mode') throw new DOMException('Blocked', 'SecurityError')
          return setItem.call(this, key, value)
        }
      }
    }, storage)
    await login(page)
    await expect(page.locator('.media-feed .file-row')).toHaveCount(7)
    await selectMode(page, 'explorer')
    await expect(page.locator('.folder-card')).toHaveCount(6)
    await selectMode(page, 'player')
    await expect(page.locator('.media-feed .file-row')).toHaveCount(7)
  })
}

