async function openVideo(page: Page, name = 'My Holiday Recording 2026.mp4') {
  await page.locator('.file-main').filter({ hasText: name }).click()
  const video = page.locator('video')
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.readyState)).toBeGreaterThanOrEqual(1)
  return video
}

// A video starts playing as soon as it opens. Tests that assert exact positions must
// pin that state first rather than race whatever autoplay happened to do.
async function ensurePlaying(page: Page) {
  const play = page.getByRole('button', { name: 'Play', exact: true })
  if (await play.isVisible().catch(() => false)) await play.click()
  await expect.poll(() => page.locator('video').evaluate((element: HTMLVideoElement) => element.paused)).toBe(false)
}

async function ensurePaused(page: Page) {
  const pause = page.getByRole('button', { name: 'Pause', exact: true })
  if (await pause.isVisible().catch(() => false)) await pause.click()
  await expect.poll(() => page.locator('video').evaluate((element: HTMLVideoElement) => element.paused)).toBe(true)
}

